// Bundle the ledger cloud function into a single self-contained CommonJS file
// that CloudBase's Node runtime can load via `exports.main`.
//
// Why bundle: the function imports workspace packages (@family-ledger/calc,
// @family-ledger/shared) and decimal.js. CloudBase deploys ONE function folder
// with its own node_modules; bundling inlines the workspace code so we don't
// have to publish those packages or hand-copy dist trees. @cloudbase/node-sdk
// is provided/installed by the CloudBase function environment, so it remains
// external to the application bundle.
//
// Output: dist-bundle/index.js (+ a minimal package.json declaring exports.main
// as the handler). Deploy the dist-bundle/ folder as the `ledger` function.

import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fnRoot = resolve(here, '..');
const outDir = resolve(fnRoot, 'dist-bundle');

await mkdir(outDir, { recursive: true });

await build({
  entryPoints: [resolve(fnRoot, 'src/index.ts')],
  outfile: resolve(outDir, 'index.js'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  external: ['@cloudbase/node-sdk'],
  // Re-export `main` as a CommonJS named export so index.main resolves.
  footer: { js: 'module.exports = { main };' },
  banner: {
    js: '// GENERATED by scripts/bundle.mjs — do not edit. Source: src/.',
  },
  logLevel: 'info',
});

// Minimal package.json for the deployed function folder.
await writeFile(
  resolve(outDir, 'package.json'),
  JSON.stringify(
    {
      name: 'ledger',
      version: '0.1.0',
      main: 'index.js',
      dependencies: {
        '@cloudbase/node-sdk': '^3.9.0',
      },
    },
    null,
    2,
  ) + '\n',
);

console.log('Bundled -> cloud/functions/ledger/dist-bundle/');
